"""Interfaces the trading daemon depends on. Django implements them for real runs;
tests use the in-memory versions in services/trader/memory.py."""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from typing import Protocol

import pandas as pd

from nextrade_core.data.candles import Timeframe


class MarketSource(Protocol):
    def frame(self, symbol: str, timeframe: Timeframe, bars: int, now: datetime) -> pd.DataFrame:
        """Last `bars` CLOSED bars as an OHLCV float frame."""
    def last_closed_bar(self, symbol: str, timeframe: Timeframe, now: datetime) -> datetime | None: ...
    def latest_quote(self, symbol: str) -> tuple[Decimal, Decimal, datetime] | None: ...
    def data_ok(self, symbol: str, now: datetime) -> bool: ...


class TradingStore(Protocol):
    def record_signal(self, run_id: int, signal, regime: str | None) -> int: ...
    def record_opportunity(self, signal_id: int, opp) -> int: ...
    def record_risk(self, opportunity_id: int, decision) -> None: ...
    def save_order(self, run_id: int, order, purpose: str, position_id: int | None) -> None: ...
    def open_position(self, run_id: int, **fields) -> int: ...
    def update_position(self, position_id: int, **fields) -> None: ...
    def close_position(self, position_id: int, **fields) -> None: ...
    def open_positions(self, run_id: int) -> list[dict]: ...
    def recent_closed_pnls(self, run_id: int, limit: int) -> list[Decimal]: ...
    def ledger(self, run_id: int, at: datetime, asset: str, amount: Decimal, kind: str, ref: str) -> None: ...
    def equity_snapshot(self, run_id: int, **fields) -> None: ...
    def equity_history(self, run_id: int) -> list[tuple[datetime, Decimal]]: ...
    def heartbeat(self, process: str, at: datetime, detail: dict) -> None: ...
    def alert(self, level: str, kind: str, message: str) -> None: ...
